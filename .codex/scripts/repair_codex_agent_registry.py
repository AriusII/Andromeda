#!/usr/bin/env python3
from __future__ import annotations

from pathlib import Path
import tomllib
import re

ROOT = Path.cwd()
CONFIG = ROOT / ".codex" / "config.toml"
AGENTS_DIR = ROOT / ".codex" / "agents"

HEADER_KEYS = {"model", "model_reasoning_effort", "sandbox_mode", "approval_policy", "commit_attribution"}
DEFAULT_AGENT_GLOBALS = {
    "max_threads",
    "max_depth",
    "job_max_runtime_seconds",
    "interrupt_message",
}


def quote(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return repr(value)
    if isinstance(value, list):
        return "[" + ", ".join(quote(v) for v in value) + "]"
    s = str(value).replace('\\', '\\\\').replace('"', '\\"')
    return f'"{s}"'


def sanitize_description(text: str) -> str:
    return " ".join(text.strip().split()).replace('"', "'")


def parse_agent_file(path: Path) -> tuple[str, str]:
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    name = data.get("name")
    if not isinstance(name, str) or not name.strip():
        name = path.stem
    description = data.get("description")
    if not isinstance(description, str) or not description.strip():
        instructions = data.get("developer_instructions")
        if isinstance(instructions, str) and instructions.strip():
            first = next((line.strip("# ").strip() for line in instructions.splitlines() if line.strip()), "Codex agent")
            description = first
        else:
            description = f"Codex agent for {name.replace('-', ' ')}."
    return name.strip(), sanitize_description(description)


def main() -> int:
    if not AGENTS_DIR.exists():
        raise SystemExit("Missing .codex/agents directory")

    original = {}
    if CONFIG.exists():
        original = tomllib.loads(CONFIG.read_text(encoding="utf-8"))

    header = {k: v for k, v in original.items() if k in HEADER_KEYS}
    features = original.get("features", {}) if isinstance(original.get("features", {}), dict) else {}
    old_agents = original.get("agents", {}) if isinstance(original.get("agents", {}), dict) else {}
    agent_defaults = original.get("agent_defaults", {}) if isinstance(original.get("agent_defaults", {}), dict) else {}

    # Recover mistakenly placed scalar keys from [agents].
    for key, value in list(old_agents.items()):
        if key in DEFAULT_AGENT_GLOBALS and not isinstance(value, dict):
            agent_defaults[key] = value

    if not header:
        header = {
            "model": "gpt-5.5-pro",
            "model_reasoning_effort": "high",
            "sandbox_mode": "workspace-write",
            "approval_policy": "on-request",
        }

    if not features:
        features = {
            "child_agents_md": True,
            "hooks": True,
            "codex_git_commit": True,
        }

    agent_entries: list[tuple[str, str, str]] = []
    seen: set[str] = set()
    for agent_file in sorted(AGENTS_DIR.glob("*.toml")):
        name, description = parse_agent_file(agent_file)
        if name in seen:
            raise SystemExit(f"Duplicate agent name discovered: {name}")
        seen.add(name)
        rel = agent_file.relative_to(CONFIG.parent).as_posix()
        agent_entries.append((name, rel, description))

    lines: list[str] = []
    lines.append("# Andromeda Codex configuration")
    lines.append("# Regenerated by .codex/scripts/repair_codex_agent_registry.py")
    for key in ["model", "model_reasoning_effort", "sandbox_mode", "approval_policy", "commit_attribution"]:
        if key in header:
            lines.append(f"{key} = {quote(header[key])}")
    lines.append("")

    if features:
        lines.append("[features]")
        for key in sorted(features):
            lines.append(f"{key} = {quote(features[key])}")
        lines.append("")

    if agent_defaults:
        lines.append("[agent_defaults]")
        for key in sorted(agent_defaults):
            lines.append(f"{key} = {quote(agent_defaults[key])}")
        lines.append("")

    lines.append("# Agent registry")
    for name, rel, description in agent_entries:
        lines.append(f"[agents.{name}]")
        lines.append(f"config_file = {quote(rel)}")
        lines.append(f"description = {quote(description)}")
        lines.append("")

    CONFIG.parent.mkdir(parents=True, exist_ok=True)
    CONFIG.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"Regenerated {CONFIG} with {len(agent_entries)} registered agents.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
